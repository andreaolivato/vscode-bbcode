/**
 * Regenerates `docs/tags.md` from the tag registry, so the reference can never
 * drift from what the parser actually supports.
 *
 * Run `npm run docs` after changing `src/bbcode/tags.ts`.
 */
import { writeFileSync } from 'node:fs';

import { CATEGORY_LABELS, DIALECTS, TAG_DEFINITIONS } from '../out/bbcode/tags.js';

const DIALECT_LABELS = {
    generic: 'Generic',
    phpbb: 'phpBB',
    vbulletin: 'vBulletin',
    xenforo: 'XenForo',
    smf: 'SMF',
    mybb: 'MyBB',
    steam: 'Steam',
};

const KIND_LABELS = {
    inline: 'inline',
    block: 'block',
    void: 'no closing tag',
    listItem: 'list item',
};

const escape = (value) => value.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (value) => `\`${value.replace(/`/g, '')}\``;

const byCategory = new Map();
for (const def of TAG_DEFINITIONS) {
    if (!byCategory.has(def.category)) {
        byCategory.set(def.category, []);
    }
    byCategory.get(def.category).push(def);
}

const lines = [
    '# BBCode tag reference',
    '',
    '<!-- Generated by `npm run docs`. Edit `src/bbcode/tags.ts` instead. -->',
    '',
    'Every tag below is understood by the preview, IntelliSense, hovers and the',
    'validator. The **Dialects** column lists the engines that provide the tag; a',
    'dash means every dialect does. Change which set is active with the',
    '`bbcode.dialect` setting.',
    '',
    `There are **${TAG_DEFINITIONS.length}** tags in total.`,
    '',
    '## Contents',
    '',
];

for (const [category, defs] of byCategory) {
    lines.push(`- [${CATEGORY_LABELS[category]}](#${slug(CATEGORY_LABELS[category])}) — ${defs.length} tags`);
}
lines.push('');

for (const [category, defs] of byCategory) {
    lines.push(`## ${CATEGORY_LABELS[category]}`, '');
    lines.push('| Tag | Aliases | Kind | Dialects | Description |');
    lines.push('| --- | --- | --- | --- | --- |');

    for (const def of defs) {
        const aliases = def.aliases?.length ? def.aliases.map(code).join(', ') : '—';
        const dialects = def.dialects?.length
            ? def.dialects.filter((name) => name !== 'generic').map((name) => DIALECT_LABELS[name]).join(', ') ||
              'Generic'
            : '—';
        lines.push(
            `| ${code(`[${def.name}]`)} | ${aliases} | ${KIND_LABELS[def.kind]} | ${dialects} | ${escape(def.description)} |`,
        );
    }
    lines.push('');

    for (const def of defs) {
        lines.push(`### \`[${def.name}]\``, '', def.description, '');
        if (def.value) {
            lines.push(`**Value** — ${def.value.description}`, '');
        }
        if (def.params?.length) {
            lines.push('**Parameters**', '');
            for (const param of def.params) {
                lines.push(`- \`${param.name}\` — ${param.description}`);
            }
            lines.push('');
        }
        lines.push('```bbcode', def.example, '```', '');
    }
}

lines.push('## Dialects', '');
lines.push('| Dialect | Tags available |');
lines.push('| --- | --- |');
for (const dialect of DIALECTS) {
    const count = TAG_DEFINITIONS.filter(
        (def) => dialect === 'generic' || !def.dialects || def.dialects.includes(dialect),
    ).length;
    lines.push(`| \`${dialect}\` (${DIALECT_LABELS[dialect]}) | ${count} |`);
}
lines.push('');

writeFileSync('docs/tags.md', lines.join('\n'));
console.log(`docs/tags.md written (${TAG_DEFINITIONS.length} tags)`);

function slug(value) {
    return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}
